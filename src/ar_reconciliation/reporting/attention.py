"""
Management attention items, generated by deterministic rules.

Each item names the rule that produced it and the transactions or invoices
it rests on, so it can be traced back to the data.  Amounts are per
currency.  No item is produced by a language model, and no customer, amount,
cause or person is invented: the "Suggested Responsible Team" is a function
from the configuration, not a named individual.
"""

from __future__ import annotations

import pandas as pd

from ar_reconciliation.reporting.config import ReportingConfig

__all__ = ["ATTENTION_COLUMNS", "management_attention"]

ATTENTION_COLUMNS = ["Priority", "Issue", "Currency", "Financial Exposure", "Items",
                     "References", "Recommended Action", "Suggested Responsible Team", "Rule"]
_ORDER = {"High": 0, "Medium": 1, "Low": 2}


def _refs(values, limit: int) -> str:
    values = [str(v) for v in values if str(v)]
    shown = ", ".join(values[:limit])
    return shown + (f" (+{len(values) - limit} more)" if len(values) > limit else "")


def management_attention(
    exceptions: pd.DataFrame,
    controls: pd.DataFrame,
    cash: pd.DataFrame,
    aging: pd.DataFrame,
    aging_detail: pd.DataFrame,
    data_quality: pd.DataFrame,
    config: ReportingConfig,
) -> pd.DataFrame:
    limit = int(config.get("attention_reference_limit", 8))
    items: list[dict] = []

    def add(priority, issue, currency, exposure, count, refs, action, team, rule):
        items.append({
            "Priority": priority, "Issue": issue, "Currency": currency, "Financial Exposure": exposure,
            "Items": count, "References": refs, "Recommended Action": action,
            "Suggested Responsible Team": team, "Rule": rule,
        })

    # 1. Failed controls
    if not controls.empty:
        failed = controls[controls["Status"] == "FAIL"]
        for _, row in failed.iterrows():
            add("High", f"{row['Control']} failed", row["Currency"], row["Variance"], 1, row["Control"],
                "Do not finalize. Investigate the Control Breaks before using any figure.",
                config.team("controls"), "Any control with status FAIL")

    open_items = exceptions[exceptions["Review Status"] != "Approved"] if not exceptions.empty else exceptions

    if not open_items.empty:
        # 2. Large unmatched receipts
        for currency, group in open_items[open_items["Match Status"] == "Unmatched"].groupby("Currency"):
            threshold = config.materiality(currency, "large_receipt")
            large = group[group["unresolved_cents"] >= threshold].sort_values("unresolved_cents", ascending=False)
            if len(large):
                add("High", "Large unmatched receipts", currency, int(large["unresolved_cents"].sum()), len(large),
                    _refs(large["Bank Receipt ID"], limit),
                    "Identify the invoices with the customer and apply, or document why the cash is held.",
                    config.team("cash_application"), f"Unmatched receipt >= {threshold / 100:,.2f} {currency}")

        # 3. Missing remittance information
        missing = open_items[open_items["Exception Category"].isin(config.get("missing_remittance_categories", []))]
        for currency, group in missing.groupby("Currency"):
            add("Medium", "Receipts without usable remittance information", currency,
                int(group["unresolved_cents"].sum()), len(group), _refs(group["Bank Receipt ID"], limit),
                "Request remittance advice from the customer; attach it as supporting evidence.",
                config.team("cash_application"), "Exception category in missing-remittance categories")

        # 4. Potential duplicate payments
        duplicates = open_items[open_items["Exception Category"].isin(config.get("duplicate_categories", []))]
        for currency, group in duplicates.groupby("Currency"):
            add("High", "Potential duplicate payments", currency, int(group["unresolved_cents"].sum()), len(group),
                _refs(group["Bank Receipt ID"], limit),
                "Confirm with the bank and the customer before applying; refund or hold on account if duplicated.",
                config.team("cash_application"), "Exception category in duplicate categories")

        # 5. Refunds / reversals
        refunds = open_items[open_items["Match Status"] == "Refund / Reversal"]
        for currency, group in refunds.groupby("Currency"):
            add("Medium", "Refunds and reversals awaiting accounting treatment", currency,
                int(group["unresolved_cents"].sum()), len(group), _refs(group["Bank Receipt ID"], limit),
                "Match each reversal to the original receipt and record the accounting treatment.",
                config.team("treasury"), "Negative receipt not yet resolved")

    # 6. Low cash application rate
    threshold = float(config.get("cash_application_rate_warning", 0))
    if not cash.empty:
        for _, row in cash.iterrows():
            application_rate = row["Cash Application Rate"]
            if application_rate is not None and application_rate < threshold:
                exposure = int(row["Held for Review"]) + int(row["Unapplied Cash"])
                add("Medium" if application_rate >= threshold / 2 else "High",
                    f"Low cash application rate ({application_rate:.1%})", row["Currency"], exposure,
                    int(row["Receipts"]), f"{row['Currency']} receipts",
                    "Prioritize the currency's held receipts in the Action & Review Queue.",
                    config.team("cash_application"), f"Cash application rate < {threshold:.0%}")

    # 7. Material AR over 90 days
    if not aging.empty:
        for _, row in aging.iterrows():
            material = config.materiality(row["Currency"], "material_balance")
            if row["AR Over 90 Days"] >= material and row["AR Over 90 Days"] > 0:
                invoices = aging_detail[(aging_detail["Currency"] == row["Currency"])
                                        & (aging_detail["Days Past Due"].fillna(0) >= 91)]
                add("High", "Material AR more than 90 days past due", row["Currency"], int(row["AR Over 90 Days"]),
                    len(invoices), _refs(invoices.sort_values("remaining", ascending=False)["Invoice Number"], limit),
                    "Escalate collection; assess the need for a bad-debt reserve under the reserve policy.",
                    config.team("collections"), f"AR over 90 days >= {material / 100:,.2f} {row['Currency']}")
            if row["Disputed / On Hold"] > 0:
                held = aging_detail[(aging_detail["Currency"] == row["Currency"])
                                    & (aging_detail["Disputed / On Hold"] == "Yes")]
                add("Medium", "Disputed or held invoices outstanding", row["Currency"], int(row["Disputed / On Hold"]),
                    len(held), _refs(held["Invoice Number"], limit),
                    "Resolve the dispute or collector hold, then collect or adjust.",
                    config.team("disputes"), "Open invoice with a dispute reason or hold status")

    # 8. Data quality
    if data_quality is not None and len(data_quality):
        add("Medium", "Input data quality issues", "All", None, len(data_quality),
            "Data Quality Checks", "Correct the source records and re-run; affected rows were held out of matching.",
            config.team("master_data"), "Any data quality issue")

    frame = pd.DataFrame(items, columns=ATTENTION_COLUMNS)
    if frame.empty:
        return frame
    frame["_o"] = frame["Priority"].map(_ORDER)
    frame["_a"] = frame["Financial Exposure"].fillna(0).abs()
    return frame.sort_values(["_o", "_a"], ascending=[True, False]).drop(columns=["_o", "_a"]).reset_index(drop=True)
